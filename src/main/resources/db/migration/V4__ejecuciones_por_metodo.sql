-- Ejecuciones con varios métodos (fase 2, ADR 04 y ADR 07).
-- Una ejecución corre de 1 a 4 métodos sobre la misma instantánea de la serie y los evalúa en una ventana
-- común. V2 suponía un solo método (columnas metodo y ventana); como resultado y metrica nunca recibieron
-- filas, se rehacen colgando de cada método ejecutado.

DROP TABLE metrica;
DROP TABLE resultado;

ALTER TABLE ejecucion DROP CONSTRAINT ck_ejecucion_ventana;
ALTER TABLE ejecucion DROP COLUMN metodo;
ALTER TABLE ejecucion DROP COLUMN ventana;

-- Versión de datos usada (última carga de la serie al ejecutar) y primer periodo evaluado; nulo si
-- ningún periodo tuvo pronóstico de todos los métodos. La clave evita duplicar una ejecución reenviada.
ALTER TABLE ejecucion ADD COLUMN carga_id BIGINT NOT NULL;
ALTER TABLE ejecucion ADD COLUMN evaluacion_desde DATE;
ALTER TABLE ejecucion ADD COLUMN clave_idempotencia VARCHAR(64);
ALTER TABLE ejecucion ADD CONSTRAINT fk_ejecucion_carga FOREIGN KEY (carga_id) REFERENCES carga (id);
ALTER TABLE ejecucion ADD CONSTRAINT uk_ejecucion_usuario_clave UNIQUE (usuario_id, clave_idempotencia);
CREATE INDEX ix_ejecucion_carga ON ejecucion (carga_id);

-- Un método por ejecución con solo sus parámetros. En el ponderado, periodos = cantidad de pesos.
CREATE TABLE metodo_ejecutado (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id  BIGINT NOT NULL,
    metodo        VARCHAR(40) NOT NULL,
    periodos      INTEGER,
    alfa          NUMERIC(11, 10),
    beta          NUMERIC(11, 10),
    CONSTRAINT uk_metodo_ejecutado UNIQUE (ejecucion_id, metodo),
    CONSTRAINT ck_metodo_ejecutado_codigo CHECK (metodo IN ('SIMPLE_MOVING_AVERAGE', 'WEIGHTED_MOVING_AVERAGE',
        'EXPONENTIAL_SMOOTHING', 'TREND_ADJUSTED_EXPONENTIAL_SMOOTHING')),
    CONSTRAINT ck_metodo_ejecutado_parametros CHECK (
        (metodo IN ('SIMPLE_MOVING_AVERAGE', 'WEIGHTED_MOVING_AVERAGE')
            AND periodos >= 1 AND alfa IS NULL AND beta IS NULL)
        OR (metodo = 'EXPONENTIAL_SMOOTHING'
            AND periodos IS NULL AND alfa > 0 AND alfa < 1 AND beta IS NULL)
        OR (metodo = 'TREND_ADJUSTED_EXPONENTIAL_SMOOTHING'
            AND periodos IS NULL AND alfa > 0 AND alfa < 1 AND beta > 0 AND beta < 1)),
    CONSTRAINT fk_metodo_ejecutado_ejecucion FOREIGN KEY (ejecucion_id) REFERENCES ejecucion (id)
);

-- Pesos del promedio ponderado; posición 0 (K0) es el dato más reciente.
CREATE TABLE peso (
    metodo_ejecutado_id  BIGINT NOT NULL,
    posicion             INTEGER NOT NULL,
    valor                NUMERIC(11, 10) NOT NULL,
    CONSTRAINT pk_peso PRIMARY KEY (metodo_ejecutado_id, posicion),
    CONSTRAINT ck_peso_posicion CHECK (posicion >= 0),
    CONSTRAINT ck_peso_valor CHECK (valor > 0 AND valor <= 1),
    CONSTRAINT fk_peso_metodo FOREIGN KEY (metodo_ejecutado_id) REFERENCES metodo_ejecutado (id)
);

-- EVALUACION: pronóstico de un periodo con real. ESTIMACION: periodo siguiente al último dato.
-- Diez decimales para conservar la comparación con el Excel a 6 decimales (respuesta 6).
CREATE TABLE resultado (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metodo_ejecutado_id  BIGINT NOT NULL,
    periodo              DATE NOT NULL,
    tipo                 VARCHAR(20) NOT NULL,
    valor_pronosticado   NUMERIC(24, 10) NOT NULL,
    valor_real           NUMERIC(18, 4),
    CONSTRAINT uk_resultado_metodo_periodo UNIQUE (metodo_ejecutado_id, periodo),
    CONSTRAINT ck_resultado_tipo CHECK (tipo IN ('EVALUACION', 'ESTIMACION')),
    CONSTRAINT ck_resultado_real CHECK ((tipo = 'EVALUACION') = (valor_real IS NOT NULL)),
    CONSTRAINT fk_resultado_metodo FOREIGN KEY (metodo_ejecutado_id) REFERENCES metodo_ejecutado (id)
);

-- Valor nulo = no calculable. MAPE se guarda como fracción, igual que la celda del Excel.
CREATE TABLE metrica (
    metodo_ejecutado_id  BIGINT NOT NULL,
    codigo               VARCHAR(20) NOT NULL,
    valor                NUMERIC(24, 10),
    pares_usados         INTEGER NOT NULL,
    pares_excluidos      INTEGER NOT NULL,
    CONSTRAINT pk_metrica PRIMARY KEY (metodo_ejecutado_id, codigo),
    CONSTRAINT ck_metrica_codigo CHECK (codigo IN ('MAD', 'MAPE')),
    CONSTRAINT ck_metrica_pares CHECK (pares_usados >= 0 AND pares_excluidos >= 0),
    CONSTRAINT fk_metrica_metodo FOREIGN KEY (metodo_ejecutado_id) REFERENCES metodo_ejecutado (id)
);
