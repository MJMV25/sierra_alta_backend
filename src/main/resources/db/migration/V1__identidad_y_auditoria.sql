-- Identidad y auditoría (figura 4 del documento de arquitectura).
-- Un usuario pertenece a exactamente un rol. Un evento puede no tener usuario (intento anónimo).
-- Los eventos no almacenan contraseñas, tokens ni identificadores de sesión.

CREATE TABLE rol (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(30) NOT NULL,
    nombre  VARCHAR(80) NOT NULL,
    CONSTRAINT uk_rol_codigo UNIQUE (codigo)
);

CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id          BIGINT NOT NULL,
    nombre_usuario  VARCHAR(50) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_nombre_usuario UNIQUE (nombre_usuario),
    CONSTRAINT ck_usuario_nombre_minusculas CHECK (nombre_usuario = LOWER(nombre_usuario)),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol (id)
);

CREATE INDEX ix_usuario_rol ON usuario (rol_id);

CREATE TABLE evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT,
    tipo        VARCHAR(40) NOT NULL,
    resultado   VARCHAR(20) NOT NULL,
    fecha       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_evento_resultado CHECK (resultado IN ('SUCCESS', 'FAILURE', 'DENIED'))
);

CREATE INDEX ix_evento_usuario ON evento (usuario_id);
CREATE INDEX ix_evento_fecha ON evento (fecha);

