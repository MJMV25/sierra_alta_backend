-- Históricos y pronósticos (figura 5 del documento de arquitectura).
-- Separa observaciones reales, ejecuciones y resultados: una estimación nunca se guarda como observación.
-- Las cantidades usan NUMERIC (precisión decimal) y las fechas de registro incluyen zona horaria.

CREATE TABLE producto (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(40) NOT NULL,
    nombre  VARCHAR(120) NOT NULL,
    activo  BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_producto_codigo UNIQUE (codigo)
);

-- Primera versión: solo periodicidad mensual. Ampliar estos CHECK mediante una nueva migración.
CREATE TABLE serie (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id   BIGINT NOT NULL,
    medida        VARCHAR(30) NOT NULL,
    periodicidad  VARCHAR(20) NOT NULL,
    unidad        VARCHAR(20) NOT NULL,
    CONSTRAINT uk_serie_producto_medida_periodicidad UNIQUE (producto_id, medida, periodicidad),
    CONSTRAINT ck_serie_medida CHECK (medida IN ('DEMANDA', 'PRODUCCION')),
    CONSTRAINT ck_serie_periodicidad CHECK (periodicidad IN ('MENSUAL')),
    CONSTRAINT fk_serie_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);

-- Una fila por serie y periodo; periodo normalizado al primer día del mes; valor no negativo.
-- Un dato ausente es la ausencia de fila, nunca un cero.
CREATE TABLE observacion (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie_id  BIGINT NOT NULL,
    periodo   DATE NOT NULL,
    valor     NUMERIC(18, 4) NOT NULL,
    CONSTRAINT uk_observacion_serie_periodo UNIQUE (serie_id, periodo),
    CONSTRAINT ck_observacion_valor CHECK (valor >= 0),
    CONSTRAINT ck_observacion_periodo_mensual CHECK (EXTRACT(DAY FROM periodo) = 1),
    CONSTRAINT fk_observacion_serie FOREIGN KEY (serie_id) REFERENCES serie (id)
);

-- Ejecución de un método sobre una serie, con autor, versión del cálculo y ventana.
CREATE TABLE ejecucion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie_id         BIGINT NOT NULL,
    usuario_id       BIGINT NOT NULL,
    fecha            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metodo           VARCHAR(40) NOT NULL,
    version_calculo  VARCHAR(20) NOT NULL,
    ventana          INTEGER NOT NULL,
    CONSTRAINT ck_ejecucion_ventana CHECK (ventana >= 1),
    CONSTRAINT fk_ejecucion_serie FOREIGN KEY (serie_id) REFERENCES serie (id),
    CONSTRAINT fk_ejecucion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE INDEX ix_ejecucion_serie ON ejecucion (serie_id);
CREATE INDEX ix_ejecucion_usuario ON ejecucion (usuario_id);

-- Instantánea inmutable de los valores usados: explica el resultado aunque el histórico se corrija después.
CREATE TABLE entrada (
    ejecucion_id  BIGINT NOT NULL,
    periodo       DATE NOT NULL,
    valor         NUMERIC(18, 4) NOT NULL,
    CONSTRAINT pk_entrada PRIMARY KEY (ejecucion_id, periodo),
    CONSTRAINT fk_entrada_ejecucion FOREIGN KEY (ejecucion_id) REFERENCES ejecucion (id)
);

-- EVALUACION: pronóstico histórico comparable con un real. ESTIMACION: periodo futuro sin real.
CREATE TABLE resultado (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id        BIGINT NOT NULL,
    periodo             DATE NOT NULL,
    tipo                VARCHAR(20) NOT NULL,
    valor_pronosticado  NUMERIC(18, 6) NOT NULL,
    valor_real          NUMERIC(18, 4),
    CONSTRAINT uk_resultado_ejecucion_periodo_tipo UNIQUE (ejecucion_id, periodo, tipo),
    CONSTRAINT ck_resultado_tipo CHECK (tipo IN ('EVALUACION', 'ESTIMACION')),
    CONSTRAINT fk_resultado_ejecucion FOREIGN KEY (ejecucion_id) REFERENCES ejecucion (id)
);

-- Valor nulo = no calculable (por ejemplo, MAPE sin pares con real distinto de cero).
CREATE TABLE metrica (
    ejecucion_id     BIGINT NOT NULL,
    codigo           VARCHAR(20) NOT NULL,
    valor            NUMERIC(18, 6),
    pares_usados     INTEGER NOT NULL,
    pares_excluidos  INTEGER NOT NULL,
    CONSTRAINT pk_metrica PRIMARY KEY (ejecucion_id, codigo),
    CONSTRAINT ck_metrica_codigo CHECK (codigo IN ('MAD', 'MAPE')),
    CONSTRAINT ck_metrica_pares CHECK (pares_usados >= 0 AND pares_excluidos >= 0),
    CONSTRAINT fk_metrica_ejecucion FOREIGN KEY (ejecucion_id) REFERENCES ejecucion (id)
);
