-- Cargas de históricos y catálogo inicial de referencias (fase 1, ADR 07).
-- Cada observación pertenece a la carga que la registró: quién, cuándo y qué rango. El id de la última
-- carga de una serie es su "versión de datos", que acompaña a pronósticos y exportaciones.

CREATE TABLE carga (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie_id       BIGINT NOT NULL,
    usuario_id     BIGINT NOT NULL,
    fecha          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad       INTEGER NOT NULL,
    periodo_desde  DATE NOT NULL,
    periodo_hasta  DATE NOT NULL,
    CONSTRAINT ck_carga_cantidad CHECK (cantidad >= 1),
    CONSTRAINT ck_carga_rango CHECK (periodo_desde <= periodo_hasta),
    CONSTRAINT fk_carga_serie FOREIGN KEY (serie_id) REFERENCES serie (id),
    CONSTRAINT fk_carga_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE INDEX ix_carga_serie ON carga (serie_id);
CREATE INDEX ix_carga_usuario ON carga (usuario_id);

-- V2 no cargó observaciones, así que la columna puede nacer obligatoria.
ALTER TABLE observacion ADD COLUMN carga_id BIGINT NOT NULL;
ALTER TABLE observacion ADD CONSTRAINT fk_observacion_carga FOREIGN KEY (carga_id) REFERENCES carga (id);
CREATE INDEX ix_observacion_carga ON observacion (carga_id);

