-- 4. Historial de cambios de la hoja. Cada guardado es una "carga" (quién, cuándo, versión de datos) y
--    aquí queda cada mes que cambió: valor anterior nulo = mes agregado; valor nuevo nulo = mes borrado.
--    Los pronósticos guardados no cambian: conservan los datos con que se calcularon (tabla entrada).
CREATE TABLE cambio_observacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_id        BIGINT NOT NULL,
    periodo         DATE NOT NULL,
    valor_anterior  NUMERIC(18, 4),
    valor_nuevo     NUMERIC(18, 4),
    CONSTRAINT ck_cambio_observacion_valores CHECK (valor_anterior IS NOT NULL OR valor_nuevo IS NOT NULL),
    CONSTRAINT ck_cambio_observacion_periodo CHECK (EXTRACT(DAY FROM periodo) = 1),
    CONSTRAINT fk_cambio_observacion_carga FOREIGN KEY (carga_id) REFERENCES carga (id)
);

CREATE INDEX ix_cambio_observacion_carga ON cambio_observacion (carga_id);
